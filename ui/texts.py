def lang() -> str:
    value = st.session_state.get('lang', 'id')
    return value if value in LANGS else 'id'


def t(key: str, **values) -> str:
    """The copy for ``key`` in the current language; ``{name}`` placeholders are filled from ``values``.

    Values are inserted as given: callers escape untrusted text before it reaches HTML.
    """
    text = COPY[lang()].get(key)
    if text is None:
        text = COPY['id'][key]                  # a missing key fails loudly in tests (KeyError)
    for name, value in values.items():
        text = text.replace('{' + name + '}', str(value))
    return text


