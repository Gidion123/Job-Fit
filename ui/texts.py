def api_text(text: str) -> str:
    """A fixed API sentence in the interface language (untranslated when unknown)."""
    text = str(text or '')
    if lang() != 'id':
        return text
    if text in _API_ID:
        return _API_ID[text]
    for prefix, local in _API_ID_PREFIX.items():
        if text.startswith(prefix):
            return local + text[len(prefix):]
    return text
